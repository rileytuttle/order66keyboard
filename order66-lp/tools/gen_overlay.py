#!/usr/bin/env python3
"""
Generate the ZMK shield overlays from the same pin map the schematic uses.

`gen_schematic.py` owns NANO_NETS and el_pos(); this imports both, so the firmware's
kscan, matrix transform and physical layout cannot drift from the hardware. That
removes a whole class of bug by construction rather than catching it in review.

Writes:
  zmk/boards/shields/order66_lp/order66_lp.overlay
  zmk/boards/shields/order66_lp/boards/nice_nano_nrf52840_zmk.overlay

Run: python3 tools/gen_overlay.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import libs  # noqa: E402
from gen_schematic import (PHYS_ROWS, PHYS_COLS, EL_ROWS, EL_COLS,  # noqa: E402
                           MOUSE_BTN_ROW, NANO_NETS, el_pos,
                           PITCH_X, GAP)

SHIELD = os.path.join(ROOT, 'zmk', 'boards', 'shields', 'order66_lp')
OUT_SHIELD = os.path.join(SHIELD, 'order66_lp.overlay')
OUT_BOARD = os.path.join(SHIELD, 'boards', 'nice_nano_nrf52840_zmk.overlay')

# ZMK layouts are in centi-key-units, so the physical gap is expressed relative to the
# column pitch rather than in millimetres. Both come from gen_schematic.
GAP_U = round(GAP / PITCH_X * 100)
KEY_U = 100


def nrf_pins():
    """nice!nano module pin number -> ('gpio0'|'gpio1', pin)."""
    out = {}
    for num, (_, _, _, name, _) in libs.pins('nice_nano:nice_nano').items():
        m = re.search(r'P(\d)\.(\d+)', name)
        if m:
            out[int(num)] = (f'gpio{m.group(1)}', int(m.group(2)))
    return out


def gpio_for(net, pinmap, nets=NANO_NETS):
    for num, n in nets.items():
        if n == net:
            port, pin = pinmap[num]
            return f'&{port} {pin}'
    raise KeyError(f'{net} not assigned in NANO_NETS')


def keymap_order():
    """Matrix-transform order = physical reading order, then the mouse buttons.

    Keeping the first 60 entries in the same physical order as the old 5x12 board means
    the existing keymap carries over untouched, with two bindings appended.
    """
    seq = []
    for r in range(PHYS_ROWS):
        for c in range(PHYS_COLS):
            seq.append(el_pos(r, c))
    for i in range(2):
        seq.append((MOUSE_BTN_ROW, i))
    return seq


def phys_layout():
    """(w, h, x, y) per key, in centi-key-units, in keymap order."""
    out = []
    for r in range(PHYS_ROWS):
        for c in range(PHYS_COLS):
            x = c * KEY_U + (GAP_U if c >= PHYS_COLS // 2 else 0)
            out.append((KEY_U, KEY_U, x, r * KEY_U))
    # Two buttons centred in the band, on the bottom row, in front of the trackpad.
    band_left = (PHYS_COLS // 2) * KEY_U - KEY_U // 2      # right edge of col 5
    for i in range(2):
        out.append((KEY_U, KEY_U, band_left + 25 + i * KEY_U, 4 * KEY_U))
    return out


def shield_overlay():
    pm = nrf_pins()
    rows = [gpio_for(f'ROW{r}', pm) for r in range(EL_ROWS)]
    cols = [gpio_for(f'COL{c}', pm) for c in range(EL_COLS)]
    order = keymap_order()
    layout = phys_layout()
    assert len(order) == len(layout) == PHYS_ROWS * PHYS_COLS + 2

    L = [f'''/*
 * order66-lp: {PHYS_ROWS}x{PHYS_COLS} Kailh Choc v1 ortholinear, split by a {GAP:.0f} mm central
 * band, plus two dedicated mouse buttons beside a Cirque trackpad.
 *
 * GENERATED by tools/gen_overlay.py from the same NANO_NETS/el_pos() that build the
 * schematic -- edit those, not this file.
 *
 * SPDX-License-Identifier: MIT
 *
 * Matrix: {EL_ROWS} rows x {EL_COLS} cols = {EL_ROWS * EL_COLS} positions, {len(order)} used.
 * Same 17 pins as a 5x12 but six more positions, which is what pays for the mouse
 * buttons. Electrical columns are shared by both halves; each half owns a block of
 * rows, so row nets stay local to one half instead of spanning the board:
 *
 *   left  half, physical cols 0-5   -> rows 0-4,  cols 0-5
 *   right half, physical cols 6-11  -> rows 5-9,  cols 0-5
 *   mouse buttons                   -> row {MOUSE_BTN_ROW},   cols 0-1
 *   spare                           -> row {MOUSE_BTN_ROW},   cols 2-5
 *
 * The physical layout is defined here rather than including ZMK's shared
 * layouts/common/ortho_5x12 -- that one has no central gap, and patching it is what
 * forced the v1.0 board's ZMK fork. A layout in our own module needs no fork.
 */

#include <dt-bindings/zmk/matrix_transform.h>
#include <physical_layouts.dtsi>

/ {{
    chosen {{
        zmk,kscan = &kscan0;
        zmk,physical-layout = &layout_order66_lp;
    }};

    layout_order66_lp: layout_order66_lp {{
        compatible = "zmk,physical-layout";
        display-name = "order66-lp";
        transform = <&matrix_transform_order66_lp>;

        keys  //                     w   h    x    y     rot    rx    ry''']

    for i, (w, h, x, y) in enumerate(layout):
        lead = '=' if i == 0 else ','
        L.append(f'            {lead} <&key_physical_attrs '
                 f'{w:3d} {h:3d} {x:4d} {y:4d}       0     0     0>')
    L.append('            ;')
    L.append('    };')
    L.append('')
    L.append('    matrix_transform_order66_lp: keymap_transform_0 {')
    L.append('        compatible = "zmk,matrix-transform";')
    L.append(f'        columns = <{EL_COLS}>;')
    L.append(f'        rows = <{EL_ROWS}>;')
    L.append('        map = <')
    for r in range(PHYS_ROWS):
        line = ' '.join(f'RC({a},{b})' for a, b in
                        [el_pos(r, c) for c in range(PHYS_COLS // 2)])
        line2 = ' '.join(f'RC({a},{b})' for a, b in
                         [el_pos(r, c) for c in range(PHYS_COLS // 2, PHYS_COLS)])
        L.append(f'            {line}   {line2}')
    L.append('            ' + ' '.join(f'RC({MOUSE_BTN_ROW},{i})' for i in range(2))
             + '   // mouse buttons')
    L.append('            >;')
    L.append('    };')
    L.append('')
    L.append('    kscan0: kscan {')
    L.append('        compatible = "zmk,kscan-gpio-matrix";')
    L.append('        wakeup-source;')
    L.append('')
    L.append('        diode-direction = "col2row";')
    L.append('')
    L.append('        row-gpios')
    for r, g in enumerate(rows):
        lead = '=' if r == 0 else ','
        L.append(f'            {lead} <{g} (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)> // ROW{r}')
    L.append('            ;')
    L.append('')
    L.append('        col-gpios')
    for c, g in enumerate(cols):
        lead = '=' if c == 0 else ','
        L.append(f'            {lead} <{g} GPIO_ACTIVE_HIGH> // COL{c}')
    L.append('            ;')
    L.append('    };')
    L.append('};')
    L.append('')
    return '\n'.join(L)


def board_overlay():
    pm = nrf_pins()
    led = gpio_for('LED_DIN_3V3', pm).split()[1]
    dr = gpio_for('TP_DR', pm)
    return f'''/*
 * nice!nano v2 specifics: the backlight chain and the Cirque trackpad.
 *
 * GENERATED by tools/gen_overlay.py -- edit NANO_NETS in tools/gen_schematic.py.
 *
 * Filename follows upstream ZMK's move to Zephyr hardware model v2: the board target
 * is `nice_nano//zmk` with v2 as a revision, and board-specific shield overlays are
 * named after the board rather than `nice_nano_v2.overlay`.
 *
 * SPDX-License-Identifier: MIT
 */

#include <dt-bindings/led/led.h>

&pinctrl {{
    spi3_default: spi3_default {{
        group1 {{
            psels = <NRF_PSEL(SPIM_MOSI, 0, {led})>;
        }};
    }};

    spi3_sleep: spi3_sleep {{
        group1 {{
            psels = <NRF_PSEL(SPIM_MOSI, 0, {led})>;
            low-power-enable;
        }};
    }};
}};

/* Backlight: {PHYS_ROWS * PHYS_COLS} SK6812MINI-E on one chain, clocked out of SPIM3 MOSI.
 * The data line goes through a 1k series resistor into a 74AHCT1G125 on the 5 V LED
 * rail, because an SK6812 at 5 V wants a logic high above ~3.5 V and the nRF52840
 * only drives 3.3 V. */
&spi3 {{
    compatible = "nordic,nrf-spim";
    status = "okay";

    pinctrl-0 = <&spi3_default>;
    pinctrl-1 = <&spi3_sleep>;
    pinctrl-names = "default", "sleep";

    led_strip: ws2812@0 {{
        compatible = "worldsemi,ws2812-spi";

        reg = <0>; /* ignored, but necessary for SPI bindings */
        spi-max-frequency = <4000000>;

        chain-length = <{PHYS_ROWS * PHYS_COLS}>; /* one per key */
        spi-one-frame = <0x70>;
        spi-zero-frame = <0x40>;
        color-mapping = <LED_COLOR_ID_GREEN LED_COLOR_ID_RED LED_COLOR_ID_BLUE>;
    }};
}};

/* Trackpad: Cirque GlidePoint TM040040 over I2C.
 *
 * No pinctrl needed -- the nice!nano already pins &i2c0 to TWIM_SDA on P0.17 and
 * TWIM_SCL on P0.20, which is exactly where the schematic puts TP_SDA/TP_SCL. The
 * board declares it as "nordic,nrf-twi"; override to twim for the DMA variant.
 *
 * The module ships strapped for SPI: remove its R1 to select I2C. VDD is on the
 * nano's switchable VCC rail, so ZMK's ext_power gates the trackpad too. */
&i2c0 {{
    compatible = "nordic,nrf-twim";
    status = "okay";
    clock-frequency = <I2C_BITRATE_FAST>;

    glidepoint: glidepoint@2a {{
        compatible = "cirque,pinnacle2";
        reg = <0x2a>;
        status = "okay";

        data-ready-gpios = <{dr} GPIO_ACTIVE_HIGH>;
        sensitivity = "2x";
        data-mode = "absolute";
        primary-tap-enable;
        sleep-mode-enable;
    }};
}};

/ {{
    chosen {{
        zmk,underglow = &led_strip;
    }};

    glidepoint_listener: glidepoint_listener {{
        compatible = "zmk,input-listener";
        device = <&glidepoint>;
    }};
}};
'''


if __name__ == '__main__':
    open(OUT_SHIELD, 'w').write(shield_overlay())
    os.makedirs(os.path.dirname(OUT_BOARD), exist_ok=True)
    open(OUT_BOARD, 'w').write(board_overlay())
    order = keymap_order()
    print(f'wrote {OUT_SHIELD}')
    print(f'      {OUT_BOARD}')
    print(f'  matrix     : {EL_ROWS} rows x {EL_COLS} cols, {len(order)} positions used '
          f'of {EL_ROWS * EL_COLS}')
    print(f'  layout     : {len(phys_layout())} keys, right half offset {GAP_U} '
          f'centi-units ({GAP:.0f} mm)')
    print(f'  LED chain  : {PHYS_ROWS * PHYS_COLS}')
